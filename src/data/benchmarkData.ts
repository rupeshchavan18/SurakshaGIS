export function computeSystemMetrics(isVerifiedOnly: boolean): SystemMetrics {
  const settlements = BENCHMARK_SETTLEMENTS.filter(s => !isVerifiedOnly || s.isVerified);
  const sites = BENCHMARK_CANDIDATE_SITES.filter(s => !isVerifiedOnly || s.isVerified);
  const hazards = BENCHMARK_HAZARD_ZONES.filter(h => !isVerifiedOnly || h.isVerified);

  const totalPop = settlements.reduce((acc, s) => acc + s.totalPopulation, 0);
  const immCount = settlements.filter(s => s.priorityHorizon === 'immediate').length;
  const totalCapacity = sites.reduce((acc, s) => acc + s.maxCarryingCapacityPop, 0);
  const allocatedPop = sites.reduce((acc, s) => acc + s.currentAllocatedPop, 0);

  const totalItems = BENCHMARK_SETTLEMENTS.length + BENCHMARK_HAZARD_ZONES.length + BENCHMARK_CANDIDATE_SITES.length;
  const verifiedItems = [
    ...BENCHMARK_SETTLEMENTS,
    ...BENCHMARK_HAZARD_ZONES,
    ...BENCHMARK_CANDIDATE_SITES,
  ].filter(i => i.isVerified).length;

  return {
    totalVulnerableSettlements: settlements.length,
    totalAtRiskPopulation: totalPop,
    immediatePriorityCount: immCount,
    activeRedZonesCount: hazards.length,
    totalCandidateSites: sites.length,
    totalCarryingCapacityAvailable: totalCapacity,
    totalAllocatedPopulation: allocatedPop,
    verifiedDatasetRatio: Math.round((verifiedItems / totalItems) * 100),
  };
}
